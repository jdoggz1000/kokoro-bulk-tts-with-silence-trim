def _sanitize_filename(name: str) -> str:
    base = re.sub(r"[^A-Za-z0-9._-]", "_", name.strip())
    if not base.lower().endswith(".wav"):
        base += ".wav"
    return base


@st.cache_resource(show_spinner=False)
def get_pipeline(lang_code: str) -> KPipeline:
    # 1) Normal init
    try:
        return KPipeline(lang_code=lang_code)
    except Exception as first_err:
        # 2) If Japanese, try unidic-lite (no network, bundled dict)
        if lang_code == "j":
            try:
                import unidic_lite  # type: ignore

                # Ensure unidic-lite is installed and discoverable
                if hasattr(unidic_lite, "install"):
                    unidic_lite.install()
                # Hint fugashi to use unidic-lite dictionary
                if hasattr(unidic_lite, "DICDIR"):
                    os.environ["FUGASHI_DIC_DIR"] = getattr(unidic_lite, "DICDIR")
                return KPipeline(lang_code=lang_code)
            except Exception:
                # 3) Fallback to full unidic download if lite is unavailable
                try:
                    import unidic  # type: ignore

                    unidic.download()
                    # Point fugashi to the installed unidic
                    if hasattr(unidic, "DICDIR"):
                        dicdir = getattr(unidic, "DICDIR")
                        os.environ["FUGASHI_DIC_DIR"] = dicdir
                        mecabrc = os.path.join(dicdir, "mecabrc")
                        if os.path.exists(mecabrc):
                            os.environ["MECABRC"] = mecabrc
                    return KPipeline(lang_code=lang_code)
                except Exception:
                    raise first_err
        # Non-Japanese or unrecoverable
        raise first_err


def parse_rows(text_area_value: str) -> List[Tuple[str, str]]:
    rows: List[Tuple[str, str]] = []
    for raw in text_area_value.splitlines():
        line = raw.strip()
        if not line:
            continue
        if "," in line:
            t, fn = line.split(",", 1)
            rows.append((t.strip(), _sanitize_filename(fn.strip())))
        else:
            # If only one token, use it as text and autogenerated filename idx
            rows.append((line, None))
    # Backfill filenames for any None entries
    auto_i = 1
    finalized: List[Tuple[str, str]] = []
    for t, fn in rows:
        if fn is None:
            fn = _sanitize_filename(f"audio_{auto_i:03d}")
            auto_i += 1
        finalized.append((t, fn))
    return finalized


def synthesize_to_wav_bytes(pipeline: KPipeline, text: str, voice: str, speed: float) -> bytes:
    generator = pipeline(text, voice=voice, speed=speed, split_pattern=r"\n+")
    for _i, (_gs, _ps, audio) in enumerate(generator):
        buf = io.BytesIO()
        sf.write(buf, audio, 24000, format="WAV")
        return buf.getvalue()
    raise RuntimeError("No audio returned by pipeline")


def trim_wav_bytes(wav_bytes: bytes, silence_threshold: float, chunk_size: int) -> bytes:
    src = io.BytesIO(wav_bytes)
    seg = AudioSegment.from_file(src, format="wav")
    trimmed = trim_tail_silence(seg, silence_threshold=silence_threshold, chunk_size=chunk_size)
    out = io.BytesIO()
    trimmed.export(out, format="wav")
    return out.getvalue()


