def trim_tail_silence(audio_segment: AudioSegment, silence_threshold: float = -50.0, chunk_size: int = 10) -> AudioSegment:
    reversed_sound = audio_segment.reverse()
    silence_duration = detect_leading_silence(
        reversed_sound,
        silence_threshold=silence_threshold,
        chunk_size=chunk_size,
    )
    return reversed_sound[silence_duration:].reverse()


